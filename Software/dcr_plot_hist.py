import tkinter as tk
from tkinter import filedialog, messagebox, ttk
import csv
import matplotlib.pyplot as plt
import numpy as np
import os

class DCRPlotterGUI:
    def __init__(self, root):
        self.root = root
        self.root.title("DCR Analysis Plotter")
        self.root.geometry("650x500")
        
        self.filepath = ""
        self.data_rows = []
        self.meas_list = []
        self.channels_list = []
        
        self.checkbox_vars = {} # Format: { 'Meas_Channel': tk.BooleanVar() }
        self.plot_dcr_raw_var = tk.BooleanVar(value=False)
        
        # Configure styles
        style = ttk.Style()
        style.configure("TLabel", font=("Helvetica", 10))
        style.configure("TButton", font=("Helvetica", 10, "bold"))
        style.configure("TCheckbutton", font=("Helvetica", 10))
        
        self.create_widgets()
        
    def create_widgets(self):
        main_frame = ttk.Frame(self.root, padding="20")
        main_frame.pack(fill=tk.BOTH, expand=True)
        
        # Load Button
        self.load_btn = ttk.Button(main_frame, text="Load DCR Results CSV", command=self.load_csv)
        self.load_btn.pack(pady=10)
        
        self.file_label = ttk.Label(main_frame, text="No file selected", wraplength=550)
        self.file_label.pack(pady=5)
        
        ttk.Separator(main_frame, orient=tk.HORIZONTAL).pack(fill=tk.X, pady=10)
        
        # Selection Frame (to hold the checkboxes dynamically)
        self.selection_frame = ttk.Frame(main_frame)
        self.selection_frame.pack(fill=tk.BOTH, expand=True)
        
        # Plot Frame
        self.plot_frame = ttk.Frame(main_frame)
        self.plot_frame.pack(fill=tk.X, pady=10)
        
        # Options Frame
        self.options_frame = ttk.Frame(self.plot_frame)
        self.options_frame.pack(pady=5)
        
        self.dcr_raw_cb = ttk.Checkbutton(self.options_frame, text="Plot DCR *with* bursts (DCR Raw) in separate window", variable=self.plot_dcr_raw_var, state=tk.DISABLED)
        self.dcr_raw_cb.pack()
        
        self.plot_btn = ttk.Button(self.plot_frame, text="Plot Selected Data", command=self.plot_data, state=tk.DISABLED)
        self.plot_btn.pack(pady=10)
        
    def load_csv(self):
        filepath = filedialog.askopenfilename(
            title="Select DCR Results CSV",
            filetypes=[("CSV Files", "*.csv"), ("All Files", "*.*")]
        )
        if not filepath:
            return
            
        self.filepath = filepath
        self.file_label.config(text=f"Loaded: {os.path.basename(filepath)}")
        
        self.parse_csv()
        
    def parse_csv(self):
        self.data_rows = []
        
        try:
            with open(self.filepath, 'r', newline='') as f:
                reader = csv.DictReader(f)
                
                # We check for the required columns based on DAQ_5GDBI.py
                required_cols = ['Meas', 'Channel', 'DCR_NoBurst_mHz_mm2', 'DCR_Raw_mHz_mm2', 'XTP_Alt_percent', 'APP_Alt_percent']
                missing = [col for col in required_cols if col not in reader.fieldnames]
                if missing:
                    messagebox.showerror("Error", f"CSV is missing required columns:\n{', '.join(missing)}\n\nPlease ensure this is a DCR results file generated by DAQ_5GDBI.py")
                    return
                
                for row in reader:
                    self.data_rows.append(row)
                    
            self.build_selection_ui()
            
        except Exception as e:
            messagebox.showerror("Error", f"Failed to read CSV:\n{e}")
            
    def build_selection_ui(self):
        # Clear previous selection
        for widget in self.selection_frame.winfo_children():
            widget.destroy()
            
        self.checkbox_vars = {}
        
        # Find unique Meas and Channels present in the CSV
        meas_set = set()
        channel_set = set()
        
        for row in self.data_rows:
            meas_set.add(row['Meas'])
            channel_set.add(row['Channel'])
            
        self.meas_list = sorted(list(meas_set))
        self.channels_list = sorted(list(channel_set))
        
        ttk.Label(self.selection_frame, text="Select combinations to plot by Meas:", font=("Helvetica", 11, "bold")).pack(anchor=tk.W, pady=(0, 10))
        
        # Create a LabelFrame for each Meas found
        for meas in self.meas_list:
            frame_meas = ttk.LabelFrame(self.selection_frame, text=f"MEAS {meas}")
            frame_meas.pack(fill=tk.X, pady=5, padx=5)
            
            for ch in self.channels_list:
                # Default all checked if there is actual data for this Meas+Channel combination
                # Wait, maybe it's better to only show checkboxes if the combination exists, 
                # but a simple matrix is easier to navigate.
                has_data = any(r['Meas'] == meas and r['Channel'] == ch for r in self.data_rows)
                
                var = tk.BooleanVar(value=has_data) # Checked by default if data exists
                self.checkbox_vars[f"{meas}_{ch}"] = var
                
                cb = ttk.Checkbutton(frame_meas, text=ch, variable=var, state=tk.NORMAL if has_data else tk.DISABLED)
                cb.pack(side=tk.LEFT, padx=15, pady=5)
                
        self.plot_btn.config(state=tk.NORMAL)
        self.dcr_raw_cb.config(state=tk.NORMAL)
        
    def plot_data(self):
        selected_combos = []
        for key, var in self.checkbox_vars.items():
            if var.get():
                meas, ch = key.split('_', 1)
                selected_combos.append({'Meas': meas, 'Channel': ch})
                
        if not selected_combos:
            messagebox.showwarning("Warning", "Please select at least one combination to plot.")
            return
            
        # Group data by the selected combinations
        data_to_plot = {}
        for combo in selected_combos:
            key = f"Meas {combo['Meas']} - {combo['Channel']}"
            data_to_plot[key] = {'DCR': [], 'XTP': [], 'APP': [], 'DCR_Raw': []}
            
        # Extract the data arrays
        for row in self.data_rows:
            for combo in selected_combos:
                if row['Meas'] == combo['Meas'] and row['Channel'] == combo['Channel']:
                    key = f"Meas {combo['Meas']} - {combo['Channel']}"
                    
                    try:
                        dcr = float(row['DCR_NoBurst_mHz_mm2'])
                        dcr_raw = float(row['DCR_Raw_mHz_mm2'])
                        xtp = float(row['XTP_Alt_percent'])
                        app = float(row['APP_Alt_percent'])
                        
                        data_to_plot[key]['DCR'].append(dcr)
                        data_to_plot[key]['DCR_Raw'].append(dcr_raw)
                        data_to_plot[key]['XTP'].append(xtp)
                        data_to_plot[key]['APP'].append(app)
                    except ValueError:
                        pass # Ignore empty or invalid string values row
                        
        self.show_plots(data_to_plot)
        
    def show_plots(self, data_to_plot):
        fig, axes = plt.subplots(1, 3, figsize=(18, 5))
        fig.suptitle(f"DCR Analysis Summary (Source: {os.path.basename(self.filepath)})", fontsize=16)
        
        metrics = [
            ('DCR', "DCR without Bursts", "DCR (mHz/mm^2)"),
            ('XTP', "XTP Alternative (>1.5 p.e.)", "XTP (%)"),
            ('APP', "APP Alternative (<5us, clean bursts)", "APP (%)")
        ]
        
        has_data = False
        
        for i, (metric_key, title, xlabel) in enumerate(metrics):
            ax = axes[i]
            metrics_plotted = 0
            
            for combo_key, values_dict in data_to_plot.items():
                data = values_dict[metric_key]
                if len(data) > 0:
                    has_data = True
                    metrics_plotted += 1
                    mean_val = np.mean(data)
                    # We use stepfilled with alpha to allow seeing overlapping histograms clearly.
                    ax.hist(data, bins=10, alpha=0.5, histtype='stepfilled', 
                            label=f'{combo_key} (Mean: {mean_val:.2f})', 
                            edgecolor='black', linewidth=1.2)
            
            ax.set_title(title)
            ax.set_xlabel(xlabel)
            ax.set_ylabel("Counts")
            
            if metrics_plotted > 0:
                ax.legend()
            ax.grid(True, alpha=0.3)
            
        if self.plot_dcr_raw_var.get():
            fig_raw, ax_raw = plt.subplots(figsize=(8, 6))
            fig_raw.suptitle(f"DCR with Bursts (Raw) Data (Source: {os.path.basename(self.filepath)})", fontsize=14)
            
            raw_plotted = 0
            for combo_key, values_dict in data_to_plot.items():
                data_raw = values_dict['DCR_Raw']
                if len(data_raw) > 0:
                    raw_plotted += 1
                    mean_val = np.mean(data_raw)
                    ax_raw.hist(data_raw, bins=10, alpha=0.5, histtype='stepfilled', 
                            label=f'{combo_key} (Mean: {mean_val:.2f})', 
                            edgecolor='black', linewidth=1.2)
                            
            ax_raw.set_title("DCR Raw (with bursts)")
            ax_raw.set_xlabel("DCR (mHz/mm^2)")
            ax_raw.set_ylabel("Counts")
            
            if raw_plotted > 0:
                ax_raw.legend()
            ax_raw.grid(True, alpha=0.3)
            plt.tight_layout()
            fig_raw.show()
            
        if not has_data:
            plt.close(fig)
            messagebox.showwarning("Warning", "No valid numerical data found for the selected combinations.")
            return
            
        plt.tight_layout()
        plt.show(block=False)

def main():
    root = tk.Tk()
    app = DCRPlotterGUI(root)
    root.mainloop()

if __name__ == "__main__":
    main()
